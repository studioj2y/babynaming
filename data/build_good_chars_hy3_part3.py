def main():
    chars = json.load(open(CHARS, encoding='utf-8'))
    existing = json.load(open(GOOD, encoding='utf-8'))
    exist_map = {it['c']: it for it in existing}
    added, dropped_base, dropped_dup = [], [], []
    for c, m, t, g in DATA3:
        if len(c) != 1:
            dropped_dup.append(c); continue
        if c in exist_map:
            dropped_dup.append(c); continue
        if c not in chars:
            dropped_base.append(c); continue
        added.append({'c': c, 'm': m, 't': t, 'g': g})
    merged = existing + added
    json.dump(merged, open(GOOD, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print(f"合并前: {len(existing)}")
    print(f"本次新增: {len(added)}")
    print(f"丢弃-底库无: {len(dropped_base)} -> {dropped_base[:15]}")
    print(f"丢弃-已存在: {len(dropped_dup)} -> {dropped_dup[:15]}")
    print(f"合并后总计: {len(merged)}")

if __name__ == '__main__':
    main()
